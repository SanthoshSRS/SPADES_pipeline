"""
KeypointDataset: loads preprocessed voxel grids + 2D keypoint labels.

Used to train KeypointPoseNet (src/models/keypoint_net.py).
Keypoint labels must be pre-generated by scripts/generate_keypoint_labels.py.

Each sample returns:
    voxel:        (C, H, W)  float32 — single-frame voxel grid
    keypoints_2d: (8, 2)     float32 — normalized [0, 1] coordinates (u/1280, v/720)
    visibility:   (8,)       bool    — True if keypoint is within image bounds
"""

import os
import h5py
import numpy as np
import torch
from torch.utils.data import Dataset
from typing import List, Optional, Tuple


class KeypointDataset(Dataset):
    """
    Dataset for training KeypointPoseNet.

    Args:
        preprocessed_dir:   Directory containing *_voxels.h5 files
        keypoint_label_dir: Directory containing *_keypoints.npz files
                            (generated by scripts/generate_keypoint_labels.py)
        sequence_ids:       List of sequence IDs to include (e.g. ['RT000', ...])
        min_visible:        Skip frames with fewer visible keypoints than this (default: 4)
        transform:          Optional callable applied to the raw voxel np.ndarray
    """

    IMG_W = 1280
    IMG_H = 720

    def __init__(
        self,
        preprocessed_dir: str,
        keypoint_label_dir: str,
        sequence_ids: List[str],
        min_visible: int = 4,
        transform: Optional[callable] = None,
    ):
        self.preprocessed_dir   = preprocessed_dir
        self.keypoint_label_dir = keypoint_label_dir
        self.min_visible        = min_visible
        self.transform          = transform

        # List of (seq_id, frame_idx) tuples
        self.samples: List[Tuple[str, int]] = []

        # Cache all keypoint arrays in memory (~11 MB for 300 sequences) so
        # __getitem__ never opens the npz file — only h5 voxel files are opened
        # fresh per __getitem__ call (same pattern as SPADESVoxelDataset which
        # works reliably with num_workers=8 fork on this server).
        self._kp_cache: dict = {}   # seq_id → {'kp_2d': (N,8,2), 'vis': (N,8)}

        self._build_index(sequence_ids)

        print(
            f"KeypointDataset: {len(self.samples)} frames "
            f"from {len(sequence_ids)} sequences "
            f"(min_visible={min_visible})"
        )

    def _build_index(self, sequence_ids: List[str]):
        for seq_id in sequence_ids:
            voxel_path = os.path.join(self.preprocessed_dir,   f"{seq_id}_voxels.h5")
            kp_path    = os.path.join(self.keypoint_label_dir, f"{seq_id}_keypoints.npz")

            if not os.path.exists(voxel_path):
                print(f"  Warning: {voxel_path} not found, skipping")
                continue
            if not os.path.exists(kp_path):
                print(f"  Warning: {kp_path} not found — run "
                      f"scripts/generate_keypoint_labels.py first, skipping")
                continue

            kp_data    = np.load(kp_path)
            visibility = kp_data['visibility']   # (N, 8) bool

            # Cache so __getitem__ never re-reads the npz
            self._kp_cache[seq_id] = {
                'kp_2d': kp_data['keypoints_2d'],   # (N, 8, 2) float32
                'vis':   visibility,                 # (N, 8) bool
            }

            with h5py.File(voxel_path, 'r') as f:
                n_voxels = f['voxels'].shape[0]

            n = min(visibility.shape[0], n_voxels)
            for i in range(n):
                if int(visibility[i].sum()) >= self.min_visible:
                    self.samples.append((seq_id, i))

    def __len__(self) -> int:
        return len(self.samples)

    def __getitem__(self, idx: int):
        seq_id, frame_idx = self.samples[idx]

        # ── Load voxel (open/close per call — same as SPADESVoxelDataset) ──────
        voxel_path = os.path.join(self.preprocessed_dir, f"{seq_id}_voxels.h5")
        with h5py.File(voxel_path, 'r') as f:
            voxel = f['voxels'][frame_idx]    # (C, H, W)

        if self.transform is not None:
            voxel = self.transform(voxel)

        # ── Load keypoints from in-memory cache ─────────────────────────────
        cache = self._kp_cache[seq_id]
        kp_2d = cache['kp_2d'][frame_idx]   # (8, 2) pixels
        vis   = cache['vis'][frame_idx]      # (8,)   bool

        # Normalize keypoints to [0, 1]
        kp_norm = kp_2d / np.array([self.IMG_W, self.IMG_H], dtype=np.float32)

        return (
            torch.from_numpy(np.array(voxel, dtype=np.float32)),   # (C, H, W)
            torch.from_numpy(kp_norm),                              # (8, 2)
            torch.from_numpy(vis),                                  # (8,) bool
        )
